import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { resolveDevServerUrl, resolvePackagerHostname } from './resolve-dev-server-url.mjs';

const appRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const infoPlistPath = path.join(appRoot, 'ios', 'StandBy', 'Info.plist');
const xcodeEnvLocalPath = path.join(appRoot, 'ios', '.xcode.env.local');

function patchInfoPlist(devServerUrl) {
  if (!fs.existsSync(infoPlistPath)) {
    console.log('Skipping Info.plist dev URL patch (ios/ not generated yet)');
    return false;
  }

  let plist = fs.readFileSync(infoPlistPath, 'utf8');
  const pattern = /<key>DEV_CLIENT_DEFAULT_LAUNCHER_URL<\/key>\s*<string>[^<]*<\/string>/;

  if (!pattern.test(plist)) {
    console.warn('DEV_CLIENT_DEFAULT_LAUNCHER_URL missing from Info.plist');
    return false;
  }

  const next = plist.replace(
    pattern,
    `<key>DEV_CLIENT_DEFAULT_LAUNCHER_URL</key>\n\t<string>${devServerUrl}</string>`,
  );

  if (next === plist) {
    return false;
  }

  fs.writeFileSync(infoPlistPath, next);
  return true;
}

function patchXcodeEnvLocal(hostname) {
  const lines = [
    '# Generated by scripts/patch-dev-client-url.mjs — do not edit',
    `export REACT_NATIVE_PACKAGER_HOSTNAME=${hostname}`,
  ];

  fs.writeFileSync(xcodeEnvLocalPath, `${lines.join('\n')}\n`);
}

const devServerUrl = resolveDevServerUrl();
const hostname = resolvePackagerHostname();
const plistPatched = patchInfoPlist(devServerUrl);
patchXcodeEnvLocal(hostname);

if (plistPatched) {
  console.log(`Patched dev client URL → ${devServerUrl}`);
} else {
  console.log(`Dev client URL already ${devServerUrl}`);
}

console.log(`Packager hostname → ${hostname}`);
